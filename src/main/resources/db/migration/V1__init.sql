CREATE TABLE before_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    situation_type_id bigint NOT NULL,
    title text,
    description text,
    scheduled_at date NOT NULL,
