CREATE TABLE after_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    before_log_id bigint NOT NULL,
    actual_score int,
    actual_score_comment text,
    free_writing text NOT NULL,
    final_diary text,
    record_status text NOT NULL,
    input_version bigint NOT NULL DEFAULT 1,
    finalized_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT fk_after_logs_before_log_id FOREIGN KEY (before_log_id) REFERENCES before_logs (id) ON DELETE CASCADE,
    CONSTRAINT ck_after_logs_record_status CHECK (record_status IN ('DRAFT', 'FINALIZED')),
    CONSTRAINT ux_after_logs_before_log_id UNIQUE (before_log_id),
    CONSTRAINT ck_after_logs_actual_score CHECK (actual_score BETWEEN 0 AND 100),
    CONSTRAINT ck_after_logs_input_version CHECK (input_version >= 1),
    CONSTRAINT ck_after_logs_finalization CHECK (
        (record_status = 'DRAFT' AND actual_score IS NULL AND final_diary IS NULL AND finalized_at IS NULL)
        OR (record_status = 'FINALIZED' AND actual_score IS NOT NULL AND final_diary IS NOT NULL AND finalized_at IS NOT NULL)
    )
);

CREATE TABLE bf_ai_feedbacks (
