-- Initial domain schema (PostgreSQL 16). Master data is seeded by a separate migration.
-- Instants use timestamptz; business dates stay date. The application supplies timestamps.
-- Visible character limits are validated by VisibleLength, not SQL code-point counts.

CREATE TABLE emotion_characters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL CONSTRAINT ux_emotion_characters_code UNIQUE,
    name text NOT NULL CONSTRAINT ux_emotion_characters_name UNIQUE,
    display_order int NOT NULL,
    active boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT ck_emotion_characters_code CHECK (code IN ('anger', 'neutral', 'happiness', 'sadness', 'surprise', 'embarrassment', 'stress'))
);

CREATE TABLE situation_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CONSTRAINT ux_situation_types_name UNIQUE,
    onboarding_selectable boolean NOT NULL,
    before_selectable boolean NOT NULL,
    display_order int NOT NULL,
    active boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE body_symptoms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CONSTRAINT ux_body_symptoms_name UNIQUE,
    description text,
    symptom_type text NOT NULL,
    onboarding_selectable boolean NOT NULL,
    after_selectable boolean NOT NULL,
    display_order int NOT NULL,
    active boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT ck_body_symptoms_symptom_type CHECK (symptom_type IN ('physical', 'behavioral', 'other'))
);

CREATE TABLE distortion_tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CONSTRAINT ux_distortion_tags_name UNIQUE,
    definition text NOT NULL,
    example_thoughts jsonb NOT NULL,
    self_questions jsonb NOT NULL,
    reframes jsonb NOT NULL,
    display_order int NOT NULL,
    theme_color text,
    illustration_key text,
    active boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT ck_distortion_tags_example_thoughts CHECK (jsonb_typeof(example_thoughts) = 'array' AND NOT jsonb_path_exists(example_thoughts, '$[*] ? (@.type() != "string")')),
    CONSTRAINT ck_distortion_tags_self_questions CHECK (jsonb_typeof(self_questions) = 'array' AND NOT jsonb_path_exists(self_questions, '$[*] ? (@.type() != "string")')),
    CONSTRAINT ck_distortion_tags_reframes CHECK (jsonb_typeof(reframes) = 'array' AND NOT jsonb_path_exists(reframes, '$[*] ? (@.type() != "string")'))
);

CREATE TABLE positive_solutions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    situation_type_id bigint,
    category_code text NOT NULL,
    category_name text NOT NULL,
    title text NOT NULL,
    solution_content text NOT NULL,
    active boolean NOT NULL,
    display_order int NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT fk_positive_solutions_situation_type_id FOREIGN KEY (situation_type_id) REFERENCES situation_types (id) ON DELETE RESTRICT,
    CONSTRAINT ck_positive_solutions_category_code CHECK (category_code IN ('awareness', 'evidence_check', 'reframing', 'body_regulation', 'resilience'))
);

CREATE TABLE anxiety_patterns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL CONSTRAINT ux_anxiety_patterns_code UNIQUE,
    name text NOT NULL,
    description text,
    active boolean NOT NULL,
    display_order int NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL,
    password_hash text,
    password_changed_at timestamptz,
    email_verified_at timestamptz,
    failed_login_count int NOT NULL DEFAULT 0,
    failed_login_window_started_at timestamptz,
    login_locked_until timestamptz,
    nickname text NOT NULL,
    representative_character_id bigint NOT NULL,
    current_emotion_code text,
    gender text,
    birth_year int,
    onboarding_completed boolean NOT NULL DEFAULT false,
    onboarding_completed_at timestamptz,
    data_generation bigint NOT NULL DEFAULT 0,
    account_status text NOT NULL,
    baseline_discomfort_score int,
    notification_time time,
    after_reminder_enabled boolean NOT NULL,
    weekly_report_start_day text NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT fk_users_representative_character_id FOREIGN KEY (representative_character_id) REFERENCES emotion_characters (id) ON DELETE RESTRICT,
    CONSTRAINT fk_users_current_emotion_code FOREIGN KEY (current_emotion_code) REFERENCES emotion_characters (code) ON DELETE RESTRICT,
    CONSTRAINT ck_users_gender CHECK (gender IN ('female', 'male')),
    CONSTRAINT ck_users_account_status CHECK (account_status IN ('onboarding', 'active', 'deleting')),
    CONSTRAINT ck_users_weekly_report_start_day CHECK (weekly_report_start_day IN ('sun', 'mon')),
    CONSTRAINT ck_users_email_trimmed CHECK (email = btrim(email) AND email <> ''),
    CONSTRAINT ck_users_failed_login_count CHECK (failed_login_count >= 0),
    CONSTRAINT ck_users_data_generation CHECK (data_generation >= 0),
    CONSTRAINT ck_users_baseline_score CHECK (baseline_discomfort_score BETWEEN 0 AND 100)
);

