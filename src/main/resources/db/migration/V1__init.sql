CREATE TABLE user_insights (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    insight_type text NOT NULL,
    situation_type_id bigint,
    period_start date,
    period_end date,
    content jsonb NOT NULL,
    model_version text NOT NULL,
    computed_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT fk_user_insights_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_insights_situation_type_id FOREIGN KEY (situation_type_id) REFERENCES situation_types (id) ON DELETE RESTRICT,
    CONSTRAINT ck_user_insights_insight_type CHECK (insight_type IN ('growth', 'situation_comparison', 'distortion_stats')),
    CONSTRAINT ux_user_insights_scope UNIQUE NULLS NOT DISTINCT (user_id, insight_type, period_start, period_end, situation_type_id),
